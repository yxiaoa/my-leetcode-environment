DROP TABLE IF EXISTS Employee;
DROP TABLE IF EXISTS Department;

CREATE TABLE Employee (
    id INT,
    name VARCHAR(50),
    salary INT,
    departmentId INT
);

INSERT INTO Employee (id, name, salary, departmentId) VALUES
